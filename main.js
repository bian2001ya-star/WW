const savedLanguage = localStorage.getItem("yosra-language") || "ar";
const savedTheme = localStorage.getItem("yosra-theme") || "light";

function applyLanguage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.innerHTML = translations[lang][key];
  });
  document.querySelectorAll(".lang-active").forEach(el => el.textContent = lang.toUpperCase());
  document.querySelectorAll(".lang-toggle").forEach(el => el.setAttribute("aria-label", lang === "ar" ? "Switch to English" : "التبديل إلى العربية"));
  document.querySelectorAll(".menu-toggle").forEach(el => el.setAttribute("aria-label", lang === "ar" ? "القائمة" : "Menu"));
  document.querySelectorAll("input[name=name]").forEach(el => el.placeholder = lang === "ar" ? "اسمك" : "Your name");
  document.querySelectorAll("input[name=email]").forEach(el => el.placeholder = "name@example.com");
  document.querySelectorAll("textarea").forEach(el => el.placeholder = lang === "ar" ? "اكتب رسالتك هنا" : "Write your message here");
  localStorage.setItem("yosra-language", lang);
}

function applyTheme(theme) {
  document.documentElement.classList.toggle("dark", theme === "dark");
  document.querySelectorAll(".theme-icon").forEach(el => el.textContent = theme === "dark" ? "🌙" : "☀️");
  document.querySelectorAll(".theme-toggle").forEach(el => el.setAttribute("aria-label", theme === "dark" ? "Switch to light mode" : "Switch to dark mode"));
  localStorage.setItem("yosra-theme", theme);
}

applyLanguage(savedLanguage);
applyTheme(savedTheme);

document.querySelectorAll(".lang-toggle").forEach(button => {
  button.addEventListener("click", () => applyLanguage(document.documentElement.lang === "ar" ? "en" : "ar"));
});
document.querySelectorAll(".theme-toggle").forEach(button => {
  button.addEventListener("click", () => applyTheme(document.documentElement.classList.contains("dark") ? "light" : "dark"));
});
document.querySelectorAll(".menu-toggle").forEach(button => {
  button.addEventListener("click", () => {
    const nav = button.closest(".nav-inner").querySelector(".nav-links");
    const open = nav.classList.toggle("open");
    button.setAttribute("aria-expanded", String(open));
  });
});
document.querySelectorAll(".nav-links a").forEach(link => link.addEventListener("click", () => {
  document.querySelectorAll(".nav-links").forEach(nav => nav.classList.remove("open"));
}));

const year = document.getElementById("year");
if (year) year.textContent = new Date().getFullYear();

const observer = "IntersectionObserver" in window
  ? new IntersectionObserver(entries => entries.forEach(entry => {
      if (entry.isIntersecting) { entry.target.classList.add("visible"); observer.unobserve(entry.target); }
    }), { threshold: .12 })
  : null;
document.querySelectorAll(".reveal").forEach((el, index) => {
  el.style.transitionDelay = `${Math.min(index % 6, 3) * 70}ms`;
  if (observer) observer.observe(el); else el.classList.add("visible");
});

